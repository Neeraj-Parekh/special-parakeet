# ── Doc template with TOC hooks ─────────────────────────────────────────────
class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, "bookmark_name"):
            level = getattr(flowable, "bookmark_level", 0)
            text = getattr(flowable, "bookmark_text", "")
            key = getattr(flowable, "bookmark_key", "")
            self.notify("TOCEntry", (level, text, self.page, key))


def _bm(text, level):
    key = "h_%s" % hashlib.md5(text.encode()).hexdigest()[:8]
    return key


def add_h1(text):
    key = _bm(text, 0)
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, text), h1s)
    p.bookmark_name = key
    p.bookmark_level = 0
    p.bookmark_text = text
    p.bookmark_key = key
    rule = HRFlowable(width="100%", color=ACCENT, thickness=1.2,
                      spaceBefore=0, spaceAfter=10)
    return [CondPageBreak(H1_ORPHAN), KeepTogether([p, rule])]


def add_h2(text):
    key = _bm(text, 1)
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, text), h2s)
    p.bookmark_name = key
    p.bookmark_level = 1
    p.bookmark_text = text
    p.bookmark_key = key
    return [p]


def P(text, style=body):
    return Paragraph(text, style)


def make_table(header, rows, ratios, align_map=None, header_style=th,
               cell_styles=None, repeat=True):
    """Standard striped table. All cells wrapped in Paragraph (iron rule)."""
    widths = [r * AVAIL_W * 0.98 for r in ratios]
    data = [[Paragraph("<b>%s</b>" % h, header_style) for h in header]]
    for r_i, row in enumerate(rows):
        line = []
        for c_i, cell in enumerate(row):
            st = (cell_styles[c_i] if cell_styles else
                  (tcc if (align_map and align_map[c_i] == "c") else tc))
            line.append(Paragraph(str(cell), st))
        data.append(line)
    t = Table(data, colWidths=widths, hAlign="CENTER",
              repeatRows=1 if repeat else 0)
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("GRID", (0, 0), (-1, -1), 0.5, BORDER),
        ("LEFTPADDING", (0, 0), (-1, -1), 7),
        ("RIGHTPADDING", (0, 0), (-1, -1), 7),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]
    for i in range(1, len(data)):
        style.append(("BACKGROUND", (0, i), (-1, i),
                      TABLE_ROW_ODD if i % 2 == 0 else TABLE_ROW_EVEN))
    t.setStyle(TableStyle(style))
    return t


def stat_row(stats):
    """Row of stat callouts: [(value, label), ...] — Data-to-Ink extraction."""
    n = len(stats)
    vals = [Paragraph("<b>%s</b>" % v, stat_big) for v, _ in stats]
    labs = [Paragraph(l, stat_lab) for _, l in stats]
    t = Table([vals, labs], colWidths=[AVAIL_W * 0.98 / n] * n, hAlign="CENTER")
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), CARD_BG),
        ("BOX", (0, 0), (-1, -1), 1, ACCENT),
        ("LINEBEFORE", (1, 0), (-1, -1), 0.5, colors.white),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, 0), 10),
        ("BOTTOMPADDING", (0, 1), (-1, 1), 10),
        ("TOPPADDING", (0, 1), (-1, 1), 2),
        ("BOTTOMPADDING", (0, 0), (-1, 0), 2),
    ]))
    return t


