def _random_digits(n: int) -> str:
    """Return a string of n random digits (0-9)."""
    return "".join(random.choices(string.digits, k=n))


def _city_to_tier(city: str) -> str:
    """Map a city name to its RBI tier (tier_1/2/3). Defaults to tier_2
    for unknown cities (a conservative default — tier_2 is the
    "neutral" tier in the OrderIn schema's cost-optimizer prior).
    """
    return _CITY_TIERS.get(city, "tier_2")


def _clamp_amount(amount: float, lo: float = 299.0, hi: float = 52_000.0) -> float:
    """Clamp an amount to the OrderIn schema's (1, 1_000_000] bound +
    the realistic ₹299-₹52k e-commerce bucket. ₹299 is the threshold
    below which Indian e-commerce merchants usually don't ship COD
    (shipping cost > margin). ₹52k is the 99th-percentile order amount
    per the user's product hypothesis."""
    return round(max(lo, min(amount, hi)), 2)


