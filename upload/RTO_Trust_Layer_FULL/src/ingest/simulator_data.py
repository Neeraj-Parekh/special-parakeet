def generate_customer(seed: int | None = None) -> dict:
    """Generate a realistic Indian customer record.

    Returns a dict with the customer's name, phone, email, city, pincode,
    address, customer_id, and a city_tier (derived from city). This dict
    is shared context used by all 4 source-specific generators below so
    that correlated cross-source events share a customer.

    Args:
        seed: Optional int seed for reproducibility. When None (the
            default) uses the global ``random`` state — call
            ``random.seed(n)`` before this function for reproducibility
            across all 4 generators in a correlated batch. When set,
            ALL random draws in this function (including the pincode
            + phone digit generation) use a fresh ``random.Random(seed)``
            instance — so two calls with the same seed return the
            same customer.

    Returns:
        A customer-context dict. Not itself a valid OrderIn — the
        per-source generators below pull from this context to build
        source-specific event dicts that the source's ``normalize()``
        converts to OrderIn.
    """
    rng = random.Random(seed) if seed is not None else random
    city, pin_prefix = rng.choice(CITIES)
    # Inline the digit generation so it uses ``rng`` (NOT the global
    # random state) — otherwise seeding this function is futile.
    pincode = pin_prefix + "".join(rng.choices(string.digits, k=3))
    first = rng.choice(FIRST_NAMES)
    last = rng.choice(LAST_NAMES)
    name = f"{first} {last}"
    # Indian mobile numbers start with 6/7/8/9 — the prefix is the
    # carrier-distinguishing digit (TRAI numbering plan 2009).
    phone = "+91" + rng.choice("6789") + "".join(rng.choices(string.digits, k=9))
    # UPI VPA — standard format name@handle.
    upi_id = f"{first.lower()}.{last.lower()}@{rng.choice(UPI_HANDLES)}"
    # Customer ID — merchant's internal stable identifier (a salted hash
    # in production; here a plain CUST-NNNNNN for human readability in
    # the simulator's stdout logs).
    customer_id = f"CUST-{rng.randint(100000, 999999)}"
    return {
        "name": name,
        "phone": phone,
        "email": f"{first.lower()}.{last.lower()}{rng.randint(1000, 9999)}"
                 f"@{'gmail.com' if rng.random() > 0.3 else 'yahoo.in'}",
        "city": city,
        "pincode": pincode,
        "address": f"{rng.randint(1, 200)} {city} {pincode}",
        "customer_id": customer_id,
        "upi_id": upi_id,
        "city_tier": _city_to_tier(city),
    }


def generate_ecommerce_order(customer: dict) -> dict:
    """Generate an e-commerce order event in the OrderIn schema directly.

    The e-commerce channel's ``normalize()`` is the identity function
    (the merchant's web checkout already posts OrderIn-conformant JSON),
    so this generator returns a dict whose fields match OrderIn's
    Pydantic model exactly. After generation, the caller can either:

      * POST the dict directly to ``/v1/risk/score`` with the
        ``X-Channel: ecommerce`` header, OR
      * Publish it to the ``ingest.ecommerce`` Redis Stream (the
        stream-processor will eventually drain it).

    Amount distribution: log-normal with median ~₹1,800 + tail to
    ₹52k. This matches the RBI digital payments analytics report 2023's
    UPI P2M per-txn amount histogram (median ₹1,575; p99 ~₹48k).

    Args:
        customer: A customer-context dict from ``generate_customer()``.
            The order is associated with this customer (the
            ``customer_id`` field is pulled from the context).

    Returns:
        A dict conforming to the OrderIn Pydantic model in
        ``src/api/routes.py``.
    """
    rng = random
    # Log-normal: median = exp(mu) = exp(7.5) ≈ ₹1,808. sigma=0.8 gives
    # a heavy right tail (matches the UPI P2M amount distribution).
    amount = _clamp_amount(rng.lognormvariate(7.5, 0.8))
    payment = rng.choices(PAYMENT_MODES, weights=[0.40, 0.35, 0.25])[0]
    if payment == "UPI":
        # UPI is treated as Prepaid in the OrderIn schema (immediate
        # settlement → no COD RTO risk).
        payment = "Prepaid"
    return {
        "order_id": f"EC-ORD-{rng.randint(100000, 999999)}",
        "amount_inr": amount,
        "category": rng.choice(PRODUCT_CATEGORIES),
        "customer_id": customer["customer_id"],
        "address_quality": rng.choices(
            ["complete", "partial", "vague"], weights=[0.70, 0.20, 0.10]
        )[0],
        "city_tier": customer["city_tier"],
        "payment_method": payment,  # COD or Prepaid (UPI folded in)
        "prior_orders": rng.randint(0, 50),
        "prior_returns": rng.randint(0, 5),
        "items": rng.randint(1, 5),
        "order_hour": rng.randint(8, 23),
        "device": rng.choice(["Web", "Android App", "iOS App"]),
        "merchant_id": f"MERCH-{rng.randint(1, 20):03d}",
    }


def generate_mobile_event(customer: dict, order: dict | None = None) -> dict:
    """Generate a mobile-banking event in the mobile source's native schema.

    The mobile source's ``normalize()`` (``src/ingest/mobile.py``)
    expects these fields: ``upi_id``, ``txn_amount``,
    ``merchant_category``, ``customer_hash``, ``device_id``,
    ``payment_method``, ``txn_hour``, ``city_tier``, ``prior_orders``,
    ``prior_returns``. This generator produces exactly that schema so
    that ``mobile.normalize(event)`` returns a valid OrderIn dict.

    Mobile-banking events are always Prepaid (UPI settles immediately),
    so the ``payment_method`` field is hardcoded to "Prepaid" — matches
    the existing test assertion in ``test_ingest.py``.

    Args:
        customer: Customer-context dict from ``generate_customer()``.
        order: Optional e-commerce order dict (for correlated cross-
            source events). When provided, the mobile event's
            ``upi_id`` references the same customer's UPI VPA so the
            stream-processor's correlation detector can join the two.

    Returns:
        A dict in the mobile-banking source's native event schema.
    """
    rng = random
    # Amount: mobile banking per-txn is smaller than e-commerce per-order
    # (bill payments, recharges, P2P transfers — median ~₹800).
    amount = round(max(500.0, min(rng.lognormvariate(6.7, 0.6), 50000.0)), 2)
    return {
        "upi_id": customer.get("upi_id") or f"cust{_random_digits(6)}@{rng.choice(UPI_HANDLES)}",
        "txn_amount": amount,
        "merchant_category": rng.choice(MOBILE_CATEGORIES),
        "customer_hash": customer["customer_id"],  # already a salted hash in prod
        "device_id": rng.choice(["Android App", "iOS App", "Android Web"]),
        "payment_method": "Prepaid",  # mobile banking is always prepaid (UPI)
        "txn_hour": rng.randint(7, 22),  # banking hours (mobile still active late)
        "city_tier": customer["city_tier"],
        "prior_orders": rng.randint(0, 50),
        "prior_returns": rng.randint(0, 5),
        "event_type": rng.choice(MOBILE_EVENT_TYPES),
        "order_id": order["order_id"] if order else None,
        "event_id": f"MOB-{rng.randint(100000, 999999)}",
        "timestamp": time.time(),
    }


def generate_callcenter_event(customer: dict, order: dict | None = None) -> dict:
    """Generate a call-center webhook payload in the callcenter source's
    native schema.

    The callcenter source's ``normalize()`` (``src/ingest/callcenter.py``)
    expects these fields: ``order_id``, ``order_amount``, ``customer_id``,
    ``reason_code``, ``address_quality``, ``city_tier``,
    ``payment_method``, ``prior_orders``, ``prior_returns``, ``items``,
    ``order_hour``, ``device``, ``agent_id``. This generator produces
    exactly that schema so ``callcenter.normalize(event)`` returns a
    valid OrderIn dict.

    The ``reason_code`` becomes the OrderIn ``category`` field (the
    call center channel uses the agent's flag reason as the per-event
    discriminator — Kandula 2021's "Payment_Type as discriminator"
    insight realized via the channel + reason code).

    Args:
        customer: Customer-context dict.
        order: Optional correlated e-commerce order. When provided,
            the call references the same order_id (the agent is calling
            to confirm a specific flagged order).

    Returns:
        A dict in the call-center webhook payload schema.
    """
    rng = random
    # Call-center orders are typically flagged because something is
    # off — so the amount skews higher than e-commerce average.
    amount = round(rng.uniform(2000, 30000), 2)
    if order:
        order_id = order["order_id"]
        # When the call is about a specific order, the payment_method
        # and amount are inherited from that order (the call-center
        # agent doesn't re-key the order — they confirm the existing
        # order's details).
        amount = order.get("amount_inr", amount)
        payment = order.get("payment_method", rng.choice(["COD", "Prepaid"]))
    else:
        order_id = f"CC-FLAG-{rng.randint(100000, 999999)}"
        payment = rng.choice(["COD", "Prepaid"])
    return {
        "order_id": order_id,
        "order_amount": amount,
        "customer_id": customer["customer_id"],
        "reason_code": rng.choice(CALL_REASONS),
        "address_quality": rng.choices(
            ["complete", "partial", "vague"], weights=[0.40, 0.35, 0.25]
        )[0],  # call-center flags skew toward incomplete addresses
        "city_tier": customer["city_tier"],
        "payment_method": payment,
        "prior_orders": rng.randint(1, 20),  # call-center: usually existing customer
        "prior_returns": rng.randint(0, 3),
        "items": rng.randint(1, 5),
        "order_hour": rng.randint(8, 22),
        "device": rng.choice(["Web", "Android App", "iOS App"]),
        "agent_id": f"AGENT-{rng.randint(100, 999)}",
        # Extra call-specific fields (dropped by normalize → OrderIn):
        "call_id": f"CALL-{rng.randint(100000, 999999)}",
        "call_duration_sec": rng.randint(30, 600),
        "call_outcome": rng.choices(
            CALL_OUTCOMES, weights=[0.55, 0.20, 0.15, 0.10]
        )[0],
        "timestamp": time.time(),
    }


def generate_atm_event(customer: dict) -> dict:
    """Generate an ATM-switch-log CSV row dict in the atm source's
    native schema.

    The atm source's ``normalize()`` (``src/ingest/atm.py``) expects
    these fields: ``txn_id``, ``txn_amount``, ``card_pan_hash``,
    ``card_network``, ``atm_id``, ``atm_location``, ``txn_hour``. This
    generator produces exactly that schema so ``atm.normalize(event)``
    returns a valid OrderIn dict.

    ATM events are always Prepaid (debit card settlement is immediate)
    and carry no address info (the ATM IS the address) — both defaults
    are applied by ``atm.normalize()``.

    Args:
        customer: Customer-context dict. The ``customer_id`` is used as
            the basis for the ``card_pan_hash`` field (in production,
            the PAN hash is a salted SHA-256 of the card number — here
            we mock it as PAN-NNNNNN using the customer_id's numeric
            suffix so correlated events from the same customer join
            cleanly).

    Returns:
        A dict in the ATM-switch-log CSV row schema.
    """
    rng = random
    return {
        "txn_id": f"ATM-TXN-{rng.randint(100000, 999999)}",
        "txn_amount": float(rng.choice(ATM_AMOUNTS)),
        "card_pan_hash": f"PAN-{customer['customer_id'].rsplit('-', 1)[-1]}",
        "card_network": rng.choice(CARD_NETWORKS),
        "atm_id": f"ATM-{rng.randint(1, 50):03d}@{customer['city']}",
        "atm_location": customer["city"],
        "txn_hour": rng.randint(0, 23),
        # Extra ATM-specific fields (dropped by normalize → OrderIn):
        "txn_type": rng.choice(["withdrawal", "balance_inquiry", "pin_change"]),
        "card_last4": _random_digits(4),
        "timestamp": time.time(),
    }


# ---------------------------------------------------------------------------
# RTO risk injection.
# ---------------------------------------------------------------------------

def inject_rto_risk(order: dict) -> dict:
    """Inject RTO risk factors into an e-commerce order dict (mutates
    in place AND returns the same dict for chaining).

    The canonical RTO risk factors per the user's product hypothesis:
      * ``payment_method`` → ``COD`` (customer pays on delivery; the
        merchant bears the return-to-origin shipping cost if they refuse)
      * ``amount_inr`` → high-amount bucket (₹15k–₹45k) — the
        costly-RTO band where a refused delivery costs the merchant
        the most in reverse-logistics fees
      * ``address_quality`` → ``vague`` (incomplete address → delivery
        attempt likely fails → RTO)
      * ``prior_orders`` → 0 (new customer → no history → no trust
        score → can't discriminate legitimate first-time from fraudster)

    The 4 risk factors combined push the cost-optimizer's RTO
    probability above the REVIEW threshold (typically ~0.45) and often
    above the REJECT threshold (~0.65) — depends on the trained model
    weights at the merchant_id level.

    This function is idempotent — calling it on an already-RTO-injected
    order just re-randomizes the amount within the same high bucket.
    Safe to call on any e-commerce order dict.

    Args:
        order: An e-commerce order dict from ``generate_ecommerce_order``.

    Returns:
        The same dict (mutated in place) with RTO risk factors injected.
    """
    order["payment_method"] = "COD"
    # High-amount bucket — costly-RTO band per the user's hypothesis.
    order["amount_inr"] = float(random.choice([15000, 25000, 35000, 45000]))
    order["address_quality"] = "vague"  # incomplete address → delivery likely fails
    order["prior_orders"] = 0  # new customer → no history
    # prior_returns stays as generated (a brand-new customer has 0
    # returns, which is consistent with prior_orders=0).
    return order


