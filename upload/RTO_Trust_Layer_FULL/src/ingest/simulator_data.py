"""Realistic data generators for the multi-source ingest simulator.

Task 12-e. Produces realistic Indian e-commerce context data — customer
records, orders, mobile-banking events, call-center webhooks, ATM-switch-log
rows — that the 4 existing source modules' ``normalize()`` functions can
convert to the unified ``OrderIn`` schema (which the existing
``/v1/risk/score`` endpoint accepts).

The 4 source modules (``src/ingest/{ecommerce,mobile,callcenter,atm}.py``)
were built in Day 4 Track M against the Microsoft Fabric fraud-detection
reference architecture. Each source has its own native event schema
(Kafka topic / CSV row / webhook payload / direct REST). This module's
generators produce events in each source's *native* schema so that
calling the corresponding ``normalize()`` function yields a valid
``OrderIn`` dict — verified by the test suite in
``tests/test_simulator.py``.

Indian e-commerce context:
  * Cities + pincodes — first 3 digits of the Indian 6-digit pincode
    encode the sorting district (e.g. 400 = Mumbai, 110 = Delhi). The
    generator uses real city prefixes so the mock data lines up with
    Indian postal geography.
  * Names — common Indian first/last name combinations across regions
    (Sharma, Patel, Reddy, Nair, etc. — north/south/cultural spread).
  * Phones — +91 country code + 10 digits (matches the Indian mobile
    numbering plan, prefix 6/7/8/9).
  * UPI IDs — standard VPA format (name@bankhandle).
  * Amounts — log-normal distribution (median ~₹1,800, tail to ₹50k)
    matches the RBI digital payments analytics report 2023's per-txn
    amount histogram for UPI P2M transactions.
  * Product categories — Indian e-commerce merchant's typical vertical
    mix (Electronics, Fashion, Groceries, Home, Beauty, Books, Sports).

Cross-source correlation:
  ~20% of events share a customer context across sources — e.g. a
  customer places an e-commerce order, then receives a call-center
  confirmation call, then logs into the mobile app to track the order,
  then makes an ATM withdrawal. This correlation is what makes the
  multi-source ingest pattern valuable: a fraudster who places an
  order + immediately withdraws cash from an ATM in a different city
  in the same window is a strong RTO risk signal (the ``stream-processor``
  would catch this via a per-(customer, window) GeoIP anomaly detector).

RTO risk injection:
  ``inject_rto_risk(order)`` mutates an e-commerce order dict to add
  the canonical RTO risk factors:
    * ``payment_method`` → ``COD`` (the customer pays on delivery —
      merchant bears the return-to-origin cost if they refuse)
    * high amount (₹15k–₹45k — the costly-RTO bucket per the user's
      product hypothesis)
    * ``address_quality`` → ``vague`` (incomplete address → delivery
      likely fails → RTO)
    * ``prior_orders`` → 0 (new customer — no history → no trust score)
    * ``prior_returns`` → 0 (matches the new-customer prior — but a
      truly new customer is a weaker signal than "old customer who
      just started returning"; the model treats 0+0 as "unknown")
  ~15% of generated orders should be RTO-injected per the user's spec.

Source distribution weights (default):
  * ecommerce 0.50  — merchant web-checkout peak throughput
  * mobile    0.25  — mobile banking 2/sec peak
  * callcenter 0.15 — call-center flags 1/5sec
  * atm       0.10  — ATM batch (lowest volume, highest amount)
"""
