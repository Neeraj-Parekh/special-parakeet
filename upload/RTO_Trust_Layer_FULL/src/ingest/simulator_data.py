def pick_source(
    weights: dict[str, float] | None = None,
    rng: random.Random | None = None,
) -> str:
    """Pick a source name based on per-source weights.

    Args:
        weights: A dict mapping source name → weight. Defaults to
            ``DEFAULT_SOURCE_WEIGHTS`` (ecommerce 0.5, mobile 0.25,
            callcenter 0.15, atm 0.10).
        rng: Optional Random instance for reproducibility.

    Returns:
        One of "ecommerce", "mobile", "callcenter", "atm".
    """
    w = weights or DEFAULT_SOURCE_WEIGHTS
    sources = list(w.keys())
    vals = [w[s] for s in sources]
    r = rng or random
    return r.choices(sources, weights=vals)[0]


def generate_correlated_chain(customer: dict) -> list[dict]:
    """Generate a correlated cross-source chain for one customer.

    Returns a list of (source, event) tuples representing a realistic
    customer journey that spans all 4 sources:

      1. E-commerce order placed on the web checkout.
      2. Mobile-app login + product_view (the customer tracks the order).
      3. Call-center confirmation call (the agent verifies the order).
      4. ATM withdrawal (the customer pulls cash — possibly to pay COD).

    The chain is what the multi-source ingest pattern is valuable for:
    a fraudster who places a COD order + immediately withdraws cash
    from an ATM in a different city is a strong RTO risk signal.

    Each event's dict is in the source's native schema (matches what
    the source's ``normalize()`` expects).

    Args:
        customer: A customer-context dict.

    Returns:
        A list of (source_name, event_dict) tuples.
    """
    order = generate_ecommerce_order(customer)
    return [
        ("ecommerce", order),
        ("mobile", generate_mobile_event(customer, order)),
        ("callcenter", generate_callcenter_event(customer, order)),
        ("atm", generate_atm_event(customer)),
    ]


def normalize_for_source(source: str, event: dict) -> dict:
    """Dispatch to the source module's ``normalize()`` function.

    Convenience wrapper so the simulator's main loop doesn't have to
    import each source module individually. Returns an OrderIn-
    conformant dict by calling the source's ``normalize()`` function.

    Args:
        source: One of "ecommerce", "mobile", "callcenter", "atm".
        event: A dict in the source's native event schema.

    Returns:
        A dict conforming to the OrderIn Pydantic model.
    """
    # Lazy imports — keeps this module import-safe in test envs that
    # don't have all 4 source modules loaded (shouldn't happen, but
    # defensive against partial installs).
    if source == "ecommerce":
        from src.ingest import ecommerce
        return ecommerce.normalize(event)
    elif source == "mobile":
        from src.ingest import mobile
        return mobile.normalize(event)
    elif source == "callcenter":
        from src.ingest import callcenter
        return callcenter.normalize(event)
    elif source == "atm":
        from src.ingest import atm
        return atm.normalize(event)
    else:
        raise ValueError(f"unknown source: {source!r}")


def generate_for_source(
    source: str,
    customer: dict | None = None,
    correlated_order: dict | None = None,
) -> tuple[dict, dict]:
    """Generate one source-specific event + return (event, normalized_orderin).

    Convenience wrapper combining generation + normalization in one
    call. Used by the simulator's main loop.

    Args:
        source: One of "ecommerce", "mobile", "callcenter", "atm".
        customer: Optional pre-built customer context (for correlation).
            If None, a fresh customer is generated (uncorrelated event).
        correlated_order: Optional e-commerce order dict — used by the
            mobile + callcenter generators to tie the event to a
            specific order.

    Returns:
        A 2-tuple ``(event_dict, normalized_orderin_dict)`` where the
        first element is the source-native event (matching what
        ``<source>.normalize()`` expects) and the second is the
        OrderIn-conformant dict (the result of calling normalize on
        the first).
    """
    if customer is None:
        customer = generate_customer()
    if source == "ecommerce":
        event = generate_ecommerce_order(customer)
    elif source == "mobile":
        event = generate_mobile_event(customer, correlated_order)
    elif source == "callcenter":
        event = generate_callcenter_event(customer, correlated_order)
    elif source == "atm":
        event = generate_atm_event(customer)
    else:
        raise ValueError(f"unknown source: {source!r}")
    normalized = normalize_for_source(source, event)
    return event, normalized
