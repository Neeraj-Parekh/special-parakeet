def test_generate_correlated_chain_shares_customer_across_sources():
    """The correlated chain's 4 events all share the same customer_id
    (in the appropriate per-source form: CUST-NNNNNN for ecommerce +
    callcenter, customer_hash=CUST-NNNNNN for mobile, PAN-NNNNNN for
    ATM where NNNNNN is the customer_id's numeric suffix).
    """
    random.seed(0)
    customer = generate_customer()
    chain = generate_correlated_chain(customer)
    # 4 events: ecommerce, mobile, callcenter, atm.
    assert len(chain) == 4
    sources = [s for s, _ in chain]
    assert sources == ["ecommerce", "mobile", "callcenter", "atm"]
    # The ecommerce + callcenter events reference the order.
    ecommerce_event = chain[0][1]
    mobile_event = chain[1][1]
    callcenter_event = chain[2][1]
    atm_event = chain[3][1]
    # E-commerce: customer_id is the customer's.
    assert ecommerce_event["customer_id"] == customer["customer_id"]
    # Mobile: customer_hash is the customer_id (mirrors how the
    # mobile-banking app uses the merchant's stable id).
    assert mobile_event["customer_hash"] == customer["customer_id"]
    # Mobile event's order_id field references the ecommerce order.
    assert mobile_event["order_id"] == ecommerce_event["order_id"]
    # Callcenter: customer_id + order_id match the ecommerce event.
    assert callcenter_event["customer_id"] == customer["customer_id"]
    assert callcenter_event["order_id"] == ecommerce_event["order_id"]
    # ATM: card_pan_hash is PAN-NNNNNN where NNNNNN is the customer_id's
    # numeric suffix (the simulator's correlation key for ATM events).
    cust_suffix = customer["customer_id"].rsplit("-", 1)[-1]
    assert atm_event["card_pan_hash"] == f"PAN-{cust_suffix}"
    # Each event normalizes to a valid OrderIn.
    for source, event in chain:
        normalized = normalize_for_source(source, event)
        OrderIn(**normalized)


def test_pick_source_returns_weighted_distribution():
    """pick_source() returns the 4 sources with the expected default
    frequency distribution (ecommerce 50%, mobile 25%, callcenter 15%,
    atm 10%). Tolerant to ±5% noise."""
    random.seed(42)
    n = 4000
    counts = {s: 0 for s in DEFAULT_SOURCE_WEIGHTS}
    for _ in range(n):
        counts[pick_source()] += 1
    # Ecommerce ~50% ± 5%.
    assert 0.45 * n <= counts["ecommerce"] <= 0.55 * n
    # Mobile ~25% ± 5%.
    assert 0.20 * n <= counts["mobile"] <= 0.30 * n
    # Callcenter ~15% ± 5%.
    assert 0.10 * n <= counts["callcenter"] <= 0.20 * n
    # ATM ~10% ± 5%.
    assert 0.05 * n <= counts["atm"] <= 0.15 * n


