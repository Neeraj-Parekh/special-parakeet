def test_generate_customer_produces_indian_context():
    """The customer generator produces Indian-context fields: +91 phone,
    valid city, 6-digit pincode starting with a known city prefix.
    """
    random.seed(42)
    for _ in range(20):
        c = generate_customer()
        # Phone: +91 followed by 10 digits, first digit 6/7/8/9 (Indian
        # mobile numbering plan).
        assert c["phone"].startswith("+91")
        body = c["phone"][3:]
        assert len(body) == 10
        assert body[0] in "6789", f"mobile prefix {body[0]} not in 6789"
        # City is one of the known CITIES.
        assert c["city"] in [city for city, _ in CITIES]
        # Pincode: 6 digits, first 3 match the city's prefix.
        assert len(c["pincode"]) == 6
        city_prefix = next(p for city, p in CITIES if city == c["city"])
        assert c["pincode"].startswith(city_prefix), (
            f"pincode {c['pincode']} doesn't match city prefix {city_prefix}"
        )
        # Email + name + customer_id all populated.
        assert "@" in c["email"]
        assert " " in c["name"]  # first + last
        assert c["customer_id"].startswith("CUST-")
        # city_tier derived from city.
        assert c["city_tier"] in ("tier_1", "tier_2", "tier_3")


