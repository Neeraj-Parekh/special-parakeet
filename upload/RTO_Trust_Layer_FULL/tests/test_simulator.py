def test_inject_rto_risk_sets_canonical_rto_factors():
    """inject_rto_risk() mutates an order to carry the 4 canonical RTO
    risk factors: COD + high amount + vague address + new customer.
    """
    random.seed(42)
    c = generate_customer()
    order = generate_ecommerce_order(c)
    # Pre-condition: the order is NOT already RTO-injected (most likely
    # has a regular amount + maybe COD, maybe Prepaid).
    mutated = inject_rto_risk(dict(order))
    # Factor 1: payment_method → COD.
    assert mutated["payment_method"] == "COD"
    # Factor 2: amount in the costly-RTO band (₹15k–₹45k).
    assert 15000 <= mutated["amount_inr"] <= 45000
    # Factor 3: address_quality → vague (incomplete → delivery likely fails).
    assert mutated["address_quality"] == "vague"
    # Factor 4: prior_orders → 0 (new customer → no history).
    assert mutated["prior_orders"] == 0


def test_inject_rto_risk_is_idempotent():
    """Calling inject_rto_risk() on an already-injected order doesn't
    raise — it just re-randomizes the amount within the same band."""
    random.seed(0)
    c = generate_customer()
    order = inject_rto_risk(generate_ecommerce_order(c))
    # Second call — should not raise, should stay in the RTO band.
    order2 = inject_rto_risk(dict(order))
    assert order2["payment_method"] == "COD"
    assert 15000 <= order2["amount_inr"] <= 45000
    assert order2["address_quality"] == "vague"
    assert order2["prior_orders"] == 0


