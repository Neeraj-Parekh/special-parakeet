def test_simulator_cli_dry_run_publishes_events_without_crashing():
    """Run the simulator in --dry-run mode for 2 seconds at 10/sec +
    verify it publishes ~20 events without crashing. Captures stdout
    + parses the JSON lines to verify each line is a well-formed
    event record.
    """
    import io
    import json
    import runpy

    # Capture stdout while running the simulator's main() in-process.
    argv = [
        "run_simulator.py",
        "--duration", "2",
        "--rate", "10",
        "--dry-run",
        "--seed", "42",
    ]
    old_argv = sys.argv
    sys.argv = argv
    old_stdout = sys.stdout
    sys.stdout = io.StringIO()
    try:
        # Run the simulator's main() — sys.exit(0) is the expected exit.
        try:
            runpy.run_path(
                str(Path(__file__).resolve().parents[1] / "scripts" / "run_simulator.py"),
                run_name="__main__",
            )
        except SystemExit as e:
            assert e.code == 0, f"simulator exited non-zero: {e.code}"
        # Parse the captured stdout — each line should be a JSON event.
        captured = sys.stdout.getvalue()
        lines = [ln for ln in captured.strip().split("\n") if ln.strip()]
        assert len(lines) >= 15, (
            f"expected >=15 events in 2s@10/sec, got {len(lines)}"
        )
        events = [json.loads(ln) for ln in lines]
        # Each event has the expected fields.
        for ev in events:
            assert "source" in ev
            assert ev["source"] in ("ecommerce", "mobile", "callcenter", "atm")
            assert "stream" in ev
            assert ev["stream"].startswith("ingest.")
            assert "orderin" in ev
            # The orderin dict validates against OrderIn.
            OrderIn(**ev["orderin"])
    finally:
        sys.argv = old_argv
        sys.stdout = old_stdout
